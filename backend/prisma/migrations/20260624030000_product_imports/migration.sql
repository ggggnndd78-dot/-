  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `product_import_rows_job_row_uq` (`job_id`, `row_number`),
  INDEX `product_import_rows_job_status_idx` (`job_id`, `status`),
  INDEX `product_import_rows_product_id_idx` (`product_id`),
  INDEX `product_import_rows_listing_id_idx` (`listing_id`),
  CONSTRAINT `product_import_rows_job_id_fkey` FOREIGN KEY (`job_id`) REFERENCES `product_import_jobs`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
